'use strict';
const { test } = require('node:test');
const assert = require('node:assert');
const fs = require('node:fs');
const path = require('node:path');
const { render } = require('../scripts/sync-benchmark');
const { loadRules } = require('../src/scanner');

const repoRoot = path.join(__dirname, '..', '..');

function ruleNameToId(name) {
  const m = /^sol_(\d{3})/.exec(name || '');
  return m ? 'SOL-' + m[1] : null;
}

test('benchmark render is deterministic', () => {
  assert.equal(render(), render());
});

test('benchmark covers every machine-checkable rule', () => {
  const out = render();
  const rules = loadRules(path.join(__dirname, '..', 'rules.json'));
  const ids = new Set(rules.map((r) => ruleNameToId(r.name)).filter(Boolean));
  for (const id of ids) {
    assert.ok(out.includes(`| ${id} |`), `${id} missing from the benchmark table`);
  }
});

test('benchmark contains no missed detections or undocumented FPs (the table mirrors the gate)', () => {
  const out = render();
  assert.ok(!out.includes('!! MISSED'), 'a rule no longer fires on its vulnerable example');
  assert.ok(!out.includes('!! UNDOCUMENTED FP'), 'a fixed example fires without a fixed-still-fires.json entry');
});

test('committed BENCHMARK.md is in sync with the generator', () => {
  const committed = fs.readFileSync(path.join(repoRoot, 'BENCHMARK.md'), 'utf8').replace(/\r\n/g, '\n');
  assert.equal(committed, render(), 'BENCHMARK.md is stale — run npm run sync:benchmark');
});

test('the generated file declares itself generated and states honest scope', () => {
  const out = render();
  assert.match(out, /GENERATED by cli\/scripts\/sync-benchmark\.js/);
  assert.match(out, /\*self\*-benchmark/);
  assert.match(out, /\*\*not\*\* a third-party recall benchmark/);
});

test('every fixed-still-fires reason cites the numbered exclusion that clears it', () => {
  // The reason string is a public claim (rendered verbatim into BENCHMARK.md):
  // force each entry to point at the specific exclusion doing the work, so a
  // vague "fixed differently" entry can't launder a noise regression.
  const allow = JSON.parse(
    fs.readFileSync(path.join(repoRoot, 'examples', 'fixed-still-fires.json'), 'utf8'),
  );
  delete allow._comment;
  for (const [id, reason] of Object.entries(allow)) {
    assert.match(reason, /exclusion #\d/i, `${id}: reason must cite the numbered exclusion (got: ${reason})`);
  }
});
