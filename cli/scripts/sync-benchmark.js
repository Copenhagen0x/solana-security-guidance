'use strict';
// Generate BENCHMARK.md (repo root) from the REAL scanner run over examples/.
//   node scripts/sync-benchmark.js           regenerate BENCHMARK.md
//   node scripts/sync-benchmark.js --check    fail (exit 1) if BENCHMARK.md is stale (CI)
//
// This is a SELF-benchmark on the canonical vulnerable/fixed example pairs — it
// proves two enforced properties of the shipped patterns (both also gated by
// cli/test/examples.test.js, so a regression fails CI before it can ship):
//   1. DETECTION (anti-rot): every machine rule fires on its own vulnerable example.
//   2. FP DISCIPLINE: every fixed example is scanner-clean, or is a documented
//      exclusion-cleared case (the syntactic tripwire is retained on purpose and
//      the fix satisfies the rule's numbered exclusion — see
//      examples/fixed-still-fires.json).
// It is NOT a third-party recall benchmark; honest scope is stated in the output.

const fs = require('fs');
const path = require('path');
const { loadRules, scanContent } = require('../src/scanner');

const repoRoot = path.join(__dirname, '..', '..');
const examplesDir = path.join(repoRoot, 'examples');
const outPath = path.join(repoRoot, 'BENCHMARK.md');

const rules = loadRules(path.join(__dirname, '..', 'rules.json'));

const FIXED_STILL_FIRES = JSON.parse(
  fs.readFileSync(path.join(examplesDir, 'fixed-still-fires.json'), 'utf8'),
);
delete FIXED_STILL_FIRES._comment;

function ruleNameToId(name) {
  const m = /^sol_(\d{3})/.exec(name || '');
  return m ? 'SOL-' + m[1] : null;
}

const byId = new Map();
for (const r of rules) {
  const id = ruleNameToId(r.name);
  if (id && !byId.has(id)) byId.set(id, r);
}

function exampleExt(dir) {
  return fs.existsSync(path.join(examplesDir, dir, 'vulnerable.ts')) ? 'ts' : 'rs';
}

function scanExample(dir, which, ext) {
  const rel = `${dir}/${which}.${ext}`;
  const content = fs.readFileSync(path.join(examplesDir, dir, `${which}.${ext}`), 'utf8');
  return scanContent(content, rel, rules);
}

function render() {
  const exampleDirs = fs
    .readdirSync(examplesDir, { withFileTypes: true })
    .filter((d) => d.isDirectory() && /^sol_\d{3}_/.test(d.name))
    .map((d) => d.name)
    .sort();

  const rows = [];
  let detected = 0;
  let fixedClean = 0;
  let exclusionCleared = 0;
  for (const dir of exampleDirs) {
    const solId = 'SOL-' + dir.slice(4, 7);
    const rule = byId.get(solId);
    if (!rule) continue; // review-only rule: illustrative example, no machine matcher
    const ext = exampleExt(dir);
    const vuln = scanExample(dir, 'vulnerable', ext);
    const fixed = scanExample(dir, 'fixed', ext);
    const fires = vuln.some((f) => ruleNameToId(f.rule) === solId);
    const fixedFires = fixed.some((f) => ruleNameToId(f.rule) === solId);
    if (fires) detected++;
    let fixedVerdict;
    if (!fixedFires) {
      fixedClean++;
      fixedVerdict = 'clean';
    } else if (FIXED_STILL_FIRES[solId]) {
      exclusionCleared++;
      // Escape table-breaking characters: a `|` or newline in a reason string must
      // not split the markdown row (and silently truncate the public verdict).
      const safe = String(FIXED_STILL_FIRES[solId]).replace(/\|/g, '\\|').replace(/[\r\n]+/g, ' ');
      fixedVerdict = `exclusion-cleared — ${safe}`;
    } else {
      // examples.test.js fails CI on this state before it can ship; rendering it
      // loudly anyway so a locally-stale tree can't produce a clean-looking table.
      fixedVerdict = '!! UNDOCUMENTED FP (examples.test.js fails on this)';
    }
    rows.push({
      solId,
      tier: rule.tier || '—',
      severity: rule.severity || '—',
      detected: fires ? 'yes' : '!! MISSED',
      fixedVerdict,
    });
  }

  const total = rows.length;
  const lines = [];
  lines.push('# Benchmark — the machine-checkable rules vs. their canonical examples');
  lines.push('');
  lines.push('<!-- GENERATED by cli/scripts/sync-benchmark.js — do not edit by hand. Regenerate: cd cli && npm run sync:benchmark -->');
  lines.push('');
  lines.push('**Scope, honestly stated:** this is a *self*-benchmark over the repo\'s curated');
  lines.push('[`examples/`](examples/) — one canonical vulnerable/fixed pair per machine-checkable');
  lines.push('rule, scanned by the real shipped engine. It proves two properties that CI enforces on');
  lines.push('every change (`cli/test/examples.test.js`): the patterns **detect their canonical bug**');
  lines.push('(anti-rot) and **stay quiet on the canonical fix** (false-positive discipline, with');
  lines.push('documented exclusion-cleared cases where the tripwire is retained by design). It is');
  lines.push('**not** a third-party recall benchmark: deterministic patterns catch the bug *classes*');
  lines.push('they encode, and deeper semantic review is what the review-only rules and a');
  lines.push('[Jelleo audit](https://jelleo.com) are for.');
  lines.push('');
  lines.push(`## Scoreboard — ${total} machine-checkable rules`);
  lines.push('');
  lines.push(`- **Detection (anti-rot): ${detected}/${total}** vulnerable examples fire their rule.`);
  lines.push(`- **FP discipline: ${fixedClean}/${total} fixed examples scanner-clean**, ${exclusionCleared} exclusion-cleared (tripwire retained by design; the fix satisfies the rule's numbered exclusion).`);
  lines.push('');
  lines.push('| Rule | Tier | Severity | Vulnerable example | Fixed example |');
  lines.push('|------|------|----------|--------------------|---------------|');
  for (const r of rows) {
    lines.push(`| ${r.solId} | ${r.tier} | ${r.severity} | ${r.detected} | ${r.fixedVerdict} |`);
  }
  lines.push('');
  lines.push('## How this stays honest');
  lines.push('');
  lines.push('- CI **fails** if a rule stops firing on its vulnerable example (a regex change that');
  lines.push('  silently loses detection cannot merge), and **fails** if a fixed example fires');
  lines.push('  without a documented exclusion entry (a noisy rule change cannot merge).');
  lines.push('- This file is generated; CI fails if it is stale (`sync-benchmark.js --check`).');
  lines.push('- The exclusion-cleared list lives in [`examples/fixed-still-fires.json`](examples/fixed-still-fires.json)');
  lines.push('  with the specific exclusion each fix satisfies.');
  lines.push('');
  return lines.join('\n');
}

if (require.main === module) {
  const check = process.argv.includes('--check');
  const content = render();
  if (check) {
    const cur = fs.existsSync(outPath) ? fs.readFileSync(outPath, 'utf8').replace(/\r\n/g, '\n') : '';
    if (cur !== content) {
      console.error('BENCHMARK.md is out of sync with examples/ + rules — run `npm run sync:benchmark` (in cli/)');
      process.exit(1);
    }
    console.log('BENCHMARK.md is in sync.');
  } else {
    fs.writeFileSync(outPath, content);
    console.log(`wrote ${path.relative(repoRoot, outPath)}`);
  }
}

module.exports = { render };
